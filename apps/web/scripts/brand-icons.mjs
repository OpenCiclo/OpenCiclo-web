// Writes every file copy of the brand mark from lib/brand/sea-mark.ts:
// app/icon.svg, app/favicon.ico and, when apps/mobile exists, the Android
// launcher icons, splash drawables and brand colors. Run from apps/web with
// `npm run icons` after changing the mark. Needs Node 22.18+ (imports .ts).

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

import { BRAND, SEA_MARK_PATH } from "../lib/brand/sea-mark.ts";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ANDROID_RES = path.resolve(WEB, "../mobile/android/app/src/main/res");
const NOTE = "Generated by apps/web/scripts/brand-icons.mjs from apps/web/lib/brand/sea-mark.ts. Do not edit by hand.";

function write(file, contents) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, contents);
  console.log(path.relative(path.resolve(WEB, "../.."), file));
}

// --- Geometry -------------------------------------------------------------

/** The sea path's numbers: M x y, then C x1 y1 x2 y2 x y for each segment. */
const PATH_NUMBERS = SEA_MARK_PATH.match(/-?\d+(?:\.\d+)?/g).map(Number);

/** The sea path moved from the 32-unit box to centre (cx, cy), `scale` per unit. */
function placedSeaPath(cx, cy, scale) {
  const f = (n) => Math.round(n * 100) / 100;
  const at = (i) => `${f(cx + (PATH_NUMBERS[i] - 16) * scale)},${f(cy + (PATH_NUMBERS[i + 1] - 16) * scale)}`;
  let d = `M${at(0)}`;
  for (let i = 2; i + 5 < PATH_NUMBERS.length; i += 6) d += `C${at(i)} ${at(i + 2)} ${at(i + 4)}`;
  return `${d}Z`;
}

/** The sea outline as a polygon in the 32-unit box (Béziers flattened). */
function seaPolygon() {
  const pts = [[PATH_NUMBERS[0], PATH_NUMBERS[1]]];
  for (let i = 2; i + 5 < PATH_NUMBERS.length; i += 6) {
    const [x0, y0] = pts[pts.length - 1];
    const [x1, y1, x2, y2, x3, y3] = PATH_NUMBERS.slice(i, i + 6);
    for (let s = 1; s <= 12; s++) {
      const t = s / 12;
      const m = 1 - t;
      pts.push([
        m * m * m * x0 + 3 * m * m * t * x1 + 3 * m * t * t * x2 + t * t * t * x3,
        m * m * m * y0 + 3 * m * m * t * y1 + 3 * m * t * t * y2 + t * t * t * y3,
      ]);
    }
  }
  return pts;
}

function circlePolygon(cx, cy, r) {
  return Array.from({ length: 512 }, (_, i) => [cx + r * Math.cos((i / 512) * 2 * Math.PI), cy + r * Math.sin((i / 512) * 2 * Math.PI)]);
}

// --- Raster ---------------------------------------------------------------

/** Anti-aliased coverage (0 to 1) of a polygon on a size×size pixel grid. */
function coverage(pts, size) {
  const cov = new Float32Array(size * size);
  const SUB = 16;
  for (let y = 0; y < size; y++) {
    for (let s = 0; s < SUB; s++) {
      const yc = y + (s + 0.5) / SUB;
      const xs = [];
      for (let i = 0; i < pts.length; i++) {
        const a = pts[i];
        const b = pts[(i + 1) % pts.length];
        if (a[1] <= yc !== b[1] <= yc) xs.push(a[0] + ((yc - a[1]) / (b[1] - a[1])) * (b[0] - a[0]));
      }
      xs.sort((p, q) => p - q);
      for (let k = 0; k + 1 < xs.length; k += 2) {
        const x0 = Math.max(0, xs[k]);
        const x1 = Math.min(size, xs[k + 1]);
        for (let x = Math.floor(x0); x < Math.ceil(x1); x++) {
          cov[y * size + x] += (Math.min(x + 1, x1) - Math.max(x, x0)) / SUB;
        }
      }
    }
  }
  return cov;
}

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));

/** RGBA pixels of the mark: disc (transparent corners) with the sea on top. */
function renderMark(size, margin = 0) {
  const scale = (size - 2 * margin) / 32;
  const disc = coverage(circlePolygon(size / 2, size / 2, 16 * scale), size);
  const sea = coverage(seaPolygon().map(([x, y]) => [margin + x * scale, margin + y * scale]), size);
  const [dr, dg, db] = rgb(BRAND.disc);
  const [sr, sg, sb] = rgb(BRAND.sea);
  const out = Buffer.alloc(size * size * 4);
  for (let i = 0; i < size * size; i++) {
    const a = Math.min(1, disc[i]);
    const s = Math.min(1, sea[i]);
    const alpha = s + a * (1 - s);
    if (alpha === 0) continue;
    out[i * 4] = Math.round((sr * s + dr * a * (1 - s)) / alpha);
    out[i * 4 + 1] = Math.round((sg * s + dg * a * (1 - s)) / alpha);
    out[i * 4 + 2] = Math.round((sb * s + db * a * (1 - s)) / alpha);
    out[i * 4 + 3] = Math.round(alpha * 255);
  }
  return out;
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

function png(size, rgba) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8; // bit depth
  header[9] = 6; // RGBA
  const rows = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y++) rgba.copy(rows, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk("IHDR", header),
    pngChunk("IDAT", deflateSync(rows, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

/** An .ico holding one PNG per size. */
function ico(sizes) {
  const images = sizes.map((size) => png(size, renderMark(size)));
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(1, 2); // type: icon
  head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach((image, i) => {
    const entry = 6 + 16 * i;
    head[entry] = sizes[i] % 256;
    head[entry + 1] = sizes[i] % 256;
    head.writeUInt16LE(1, entry + 4); // color planes
    head.writeUInt16LE(32, entry + 6); // bits per pixel
    head.writeUInt32LE(image.length, entry + 8);
    head.writeUInt32LE(offset, entry + 12);
    offset += image.length;
  });
  return Buffer.concat([head, ...images]);
}

// --- Web ------------------------------------------------------------------

write(
  path.join(WEB, "app/icon.svg"),
  `<!-- The Ciclo mark: a dark disc with a round sea inside. ${NOTE} -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" role="img" aria-label="Ciclo">
  <circle cx="16" cy="16" r="16" fill="${BRAND.disc}" />
  <path d="${SEA_MARK_PATH}" fill="${BRAND.sea}" />
</svg>
`,
);
write(path.join(WEB, "app/favicon.ico"), ico([16, 32, 48]));

// --- Android --------------------------------------------------------------

if (existsSync(ANDROID_RES)) {
  const res = (file) => path.join(ANDROID_RES, file);
  const upper = (hex) => hex.toUpperCase();
  // Adaptive icons draw a 108dp layer and show the middle 72dp, so the disc
  // (the icon background) spans 72dp: 2.25dp per unit of the 32-unit box.
  const sea108 = placedSeaPath(54, 54, 72 / 32);
  const vector = (paths) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${NOTE} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${paths}
</vector>
`;
  const seaPath = (fill) => `    <path
        android:fillColor="${fill}"
        android:pathData="${sea108}" />`;

  write(res("drawable/ic_launcher_foreground.xml"), vector(seaPath(upper(BRAND.sea))));
  write(res("drawable/ic_launcher_monochrome.xml"), vector(seaPath("#FFFFFF")));
  // Splash: the system draws the disc (windowSplashScreenIconBackgroundColor);
  // this is the sea on top, in the same 108dp layout as the launcher icon.
  write(res("drawable/splash_sea.xml"), vector(seaPath("@color/brand_mark_sea")));
  // Pre-Android 12 splash: disc and sea in one drawable, centred by drawable/splash.xml.
  write(
    res("drawable/splash_mark.xml"),
    vector(`    <path
        android:fillColor="@color/brand_mark_disc"
        android:pathData="M18,54a36,36 0 1,0 72,0a36,36 0 1,0 -72,0Z" />
${seaPath("@color/brand_mark_sea")}`),
  );

  const colors = (background, disc, sea) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${NOTE} -->
<resources>
    <color name="brand_background">${upper(background)}</color>
    <color name="brand_mark_disc">${upper(disc)}</color>
    <color name="brand_mark_sea">${upper(sea)}</color>
</resources>
`;
  write(res("values/brand_colors.xml"), colors(BRAND.background, BRAND.disc, BRAND.sea));
  write(res("values-night/brand_colors.xml"), colors(BRAND.backgroundDark, BRAND.discDark, BRAND.seaDark));
  write(
    res("values/ic_launcher_background.xml"),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- ${NOTE} -->
<resources>
    <color name="ic_launcher_background">${upper(BRAND.disc)}</color>
</resources>
`,
  );

  // Android 7.x has no adaptive icons: a round bitmap, 44dp disc on a 48dp canvas.
  const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
  for (const [density, factor] of Object.entries(densities)) {
    const size = 48 * factor;
    const icon = png(size, renderMark(size, 2 * factor));
    write(res(`mipmap-${density}/ic_launcher.png`), icon);
    write(res(`mipmap-${density}/ic_launcher_round.png`), icon);
  }
}
